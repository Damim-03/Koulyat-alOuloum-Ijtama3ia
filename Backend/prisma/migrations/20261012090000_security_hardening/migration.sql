-- Security hardening:
--  * a handed-out password must be replaced before the account is used;
--  * two-step verification (TOTP) for administrators;
--  * server-side idle timeout for administrator sessions (AuthSession.lastSeenAt);
--  * the browsers an account signed in from, to flag a new one (UserDevice);
--  * the audit log (AuditLog).

-- AlterTable
ALTER TABLE `User` ADD COLUMN `mustChangePassword` BOOLEAN NOT NULL DEFAULT false,
    ADD COLUMN `totpEnabledAt` DATETIME(3) NULL,
    ADD COLUMN `totpLastStep` INTEGER NULL,
    ADD COLUMN `totpPendingSecret` VARCHAR(255) NULL,
    ADD COLUMN `totpRecoveryCodes` JSON NULL,
    ADD COLUMN `totpSecret` VARCHAR(255) NULL;

-- Every student and professor account so far was given its password by the
-- administration (a birth date, or one generated by an import). Administrators
-- chose theirs (create-admin), so they are left alone.
UPDATE `User` SET `mustChangePassword` = true WHERE `role` IN ('student', 'professor');

-- AlterTable
ALTER TABLE `Notification` MODIFY `type` ENUM('application_accepted', 'application_rejected', 'topic_approved', 'topic_rejected', 'milestone_due', 'milestone_feedback', 'defense_scheduled', 'defense_graded', 'general', 'security_alert') NOT NULL DEFAULT 'general';

-- AlterTable
ALTER TABLE `AuthSession` ADD COLUMN `lastSeenAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3);

-- CreateTable
CREATE TABLE `UserDevice` (
    `id` VARCHAR(191) NOT NULL,
    `userId` VARCHAR(191) NOT NULL,
    `deviceKey` VARCHAR(64) NOT NULL,
    `userAgent` VARCHAR(512) NULL,
    `ip` VARCHAR(64) NULL,
    `firstSeenAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `lastSeenAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),

    UNIQUE INDEX `UserDevice_userId_deviceKey_key`(`userId`, `deviceKey`),
    PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

-- CreateTable
CREATE TABLE `AuditLog` (
    `id` VARCHAR(191) NOT NULL,
    `actorId` VARCHAR(64) NULL,
    `actorRole` VARCHAR(20) NULL,
    `actorLabel` VARCHAR(191) NULL,
    `action` VARCHAR(120) NOT NULL,
    `targetType` VARCHAR(40) NULL,
    `targetId` VARCHAR(64) NULL,
    `details` JSON NULL,
    `success` BOOLEAN NOT NULL DEFAULT true,
    `ip` VARCHAR(64) NULL,
    `userAgent` VARCHAR(512) NULL,
    `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),

    INDEX `AuditLog_createdAt_idx`(`createdAt`),
    INDEX `AuditLog_actorId_createdAt_idx`(`actorId`, `createdAt`),
    INDEX `AuditLog_action_createdAt_idx`(`action`, `createdAt`),
    PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

-- AddForeignKey
ALTER TABLE `UserDevice` ADD CONSTRAINT `UserDevice_userId_fkey` FOREIGN KEY (`userId`) REFERENCES `User`(`id`) ON DELETE CASCADE ON UPDATE CASCADE;

