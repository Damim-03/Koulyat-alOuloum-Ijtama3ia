-- يُلغي دور `owner` ويُسلّم صلاحياته إلى `admin`.
--
-- كان في المنصّة مستويان إداريّان: `admin` مقيَّدٌ بجدول الصلاحيات، و`owner`
-- يتجاوز الجدول كلّه ويملك وحده حذف الحسابات. والمستويان لم يكونا يُستعملان
-- استعمالاً حقيقياً: صلاحيات النظام الأربع التي تميّز المالك
-- (MANAGE_ADMINS، VIEW_AUDIT_LOGS، MANAGE_SYSTEM_SETTINGS، SYSTEM_OVERVIEW)
-- لا يفحصها مسارٌ واحد في الشيفرة. فالفرق العمليّ الوحيد كان ثلاثة مسارات
-- حذف — وهي تنتقل إلى `admin`.
--
-- **الترتيب هنا ليس تفصيلاً**: التحويل قبل التضييق. فلو ضُيّق النوع أوّلاً
-- لوجدت MariaDB صفوفاً تحمل قيمةً لم تعد في النوع، فإمّا ترفض العملية وإمّا
-- تكتب مكانها فراغاً — وحسابٌ بدورٍ فارغ لا يدخل ولا يُدار.

-- ١) كل مالكٍ يصير مديراً. ولا رجعة: بعد هذا السطر لا يبقى في القاعدة ما
--    يدلّ على من كان مالكاً.
UPDATE `User` SET `role` = 'admin' WHERE `role` = 'owner';

-- ٢) ثم يُضيَّق النوع، فلا يُكتب `owner` بعد اليوم ولو حاول أحد.
ALTER TABLE `User` MODIFY `role` ENUM('admin', 'professor', 'student') NOT NULL;
