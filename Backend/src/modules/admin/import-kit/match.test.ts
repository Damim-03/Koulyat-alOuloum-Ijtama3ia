/**
 * المطابقة — ما لا تمرّ به ملفّات الاختبار: أرقامٌ فارسية، وما كُتب جزءٌ من
 * اسمٍ أطول، وخياراتٌ بلا حروف، وقائمةٌ تُختصر في الرسالة.
 */
import { closest, didYouMean, latinDigits, listOf } from "./match";

describe("match", () => {
  it("latinDigits: الأرقام العربية والفارسية ← لاتينية", () => {
    expect(latinDigits("٢٠٢٦/۲۰۲۷")).toBe("2026/2027");
  });

  it("closest: ما كُتب جزءٌ من الاسم ⇒ يُقترح الاسم كاملاً", () => {
    expect(closest("النفس العيادي", ["علم الاجتماع", "علم النفس العيادي"])).toBe("علم النفس العيادي");
  });

  /** خيارٌ لا حرف فيه «جزءٌ» من كلّ نصّ: لو لم يُتخطَّ لاقتُرح على كلّ ما يُكتب. */
  it("closest: خيارٌ بلا حروف لا يُقترح، ولا خيارات ⇒ لا اقتراح", () => {
    expect(closest("ماستر", ["—", "..."])).toBeUndefined();
    expect(didYouMean("ماستر", [])).toBe("");
  });

  it("listOf: أوّل n، ثم عدد الباقي", () => {
    expect(listOf(["أ", "ب", "ج"], 2)).toBe("«أ»، «ب» و1 غيرها");
    expect(listOf(["أ", "ب"])).toBe("«أ»، «ب»");
  });
});
