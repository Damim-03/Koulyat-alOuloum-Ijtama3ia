import { t } from "i18next";

/**
 * «لا يوجد» — الفراغ مكتوباً.
 *
 * كانت الشرطة «—» تسدّ هذا الموضع في المنصّة كلّها. وهي مفهومةٌ لمن بناها،
 * أمّا القارئ فيرى علامةً لا كلمة: هل الحقل فارغ؟ أم لم يُحمَّل؟ أم انكسر
 * شيء؟ فالكلمة تقطع الاحتمالات.
 *
 * وهي مؤنّثةٌ ومذكّرة، لأن العربية لا تحتمل صيغةً واحدة: «القسم لا يوجد»
 * و«الكلّية لا توجد». والاختيار عند موضع النداء، فهو وحده يعرف اسم الحقل.
 *
 * وصيغتان لا واحدة:
 *   - `noneText()` نصٌّ صرف، لما يُمرَّر خاصّيةً أو يُخزَّن في جدول بيانات؛
 *   - `<None />` عنصرٌ يحمل تنسيقه معه، لما يُكتب في JSX مباشرةً.
 *
 * والثاني هو المُفضَّل حيث أمكن: الفراغ يُكتب **ويُخفَت**، فلا ينافس
 * البياناتِ الحقيقية على انتباه العين. وبطاقةٌ فيها ثلاثة أسطرٍ بارزة تقول
 * «لا يوجد» تبدو معطوبةً لا فارغة.
 */
export const noneText = (fem = false): string =>
  t(fem ? "common.noneF" : "common.none");

/** هل هذه القيمة نائبةٌ عن الفراغ؟ يُستعمل لتخفيت ما وصل جاهزاً. */
export const isNone = (value?: string | null): boolean =>
  !value || value === noneText() || value === noneText(true);
